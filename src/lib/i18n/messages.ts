export const messages = {
  en: englishMessages,
  pt: portugueseMessages,
} satisfies Record<Locale, MessageShape>;

export type Messages = MessageShape;

export function getMessages(locale: Locale): Messages {
  return messages[locale];
}

export function translate(locale: Locale, text: string): string {
  if (locale === "en") return text;
  const translations = messages.pt.text as Record<string, string>;
  const exactTranslation = translations[text];
  if (exactTranslation) return exactTranslation;

  for (const [template, translation] of Object.entries(translations)) {
    if (!template.includes("{")) continue;
    const pattern = template
      .split(/\{[^{}]+\}/g)
      .map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
      .join("(.+?)");
    const match = new RegExp(`^${pattern}$`).exec(text);
    if (!match) continue;

    let captureIndex = 1;
    return translation.replace(/\{([^{}]+)\}/g, () => {
      const value = match[captureIndex] ?? "";
      captureIndex += 1;
      return translations[value] ?? value;
    });
  }

  return text;
}
